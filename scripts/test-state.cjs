const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
const file = path.resolve(__dirname, '../src/chapterState.ts');
const compiled = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true } }).outputText;
const loaded = new Module(file, module); loaded.filename = file; loaded.paths = module.paths; loaded._compile(compiled, file);
const { blankSave, blankAnswers, decodeSave, stepsFor, heroes, progress } = loaded.exports;
assert.deepEqual(decodeSave('{broken'), blankSave());
assert.deepEqual(decodeSave('{"version":99}'), blankSave());
const s = blankSave(); const venom = heroes.find(h => h.name === 'Venom').id;
const thor = heroes.find(h => h.name === 'Thor').id;
const deadpool = heroes.find(h => h.name === 'Deadpool');
assert.deepEqual([...deadpool.roles].sort(), ['duelist', 'strategist', 'vanguard']);
s.roles.vanguard = { decision: 'play', picks: [venom, thor], answers: { [venom]: { ...blankAnswers(), why: 'Personal draft', change: 'A proposed rework', rationale: 'A personal argument' } } };
const restored = decodeSave(JSON.stringify(s));
assert.deepEqual(restored.roles, s.roles);
assert.equal(stepsFor(restored).filter(step => step.hero).length, 6);
s.roles.vanguard.decision = 'none';
assert.equal(stepsFor(s).filter(step => step.hero).length, 0);
assert.equal(decodeSave(JSON.stringify(s)).roles.vanguard.answers[venom].rationale, 'A personal argument');
s.roles.vanguard.decision = 'play';
s.roles.vanguard.picks = [venom, venom, 'unknown-id'];
s.roles.duelist.picks = [venom]; s.roles.duelist.decision = 'play';
const sanitized = decodeSave(JSON.stringify(s));
assert.deepEqual(sanitized.roles.vanguard.picks, [venom]);
assert.equal(sanitized.roles.duelist.decision, 'unanswered');
assert.equal(progress(blankSave()), 0);
const skipped = blankSave(); skipped.skipped = stepsFor(skipped).slice(0, -1).map(s => s.id);
assert.equal(progress(skipped), 100);
console.log('State checks passed: save recovery, role validation, multi-role heroes, second favorites, retained drafts, and skip progress.');

